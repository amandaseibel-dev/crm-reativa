-- Confere o baseline antes de aplicar qualquer coisa.
do $$
declare v_com integer; v_sem integer; v_rls integer; v_pol integer; v_md5 text;
begin
  select count(*) filter (where has_table_privilege('authenticated', c.oid, 'TRUNCATE')),
         count(*) filter (where not has_table_privilege('authenticated', c.oid, 'TRUNCATE')),
         count(*) filter (where c.relrowsecurity)
    into v_com, v_sem, v_rls
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname='public' and c.relkind='r' and c.relname like '\_backup\_pos\_import\_%';

  select count(*) into v_pol from pg_policies where schemaname='public' and tablename like '\_backup\_pos\_import\_%';

  select md5(string_agg(c.relname, ',' order by c.relname)) into v_md5
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname='public' and c.relkind='r' and c.relname like '\_backup\_pos\_import\_%'
     and has_table_privilege('authenticated', c.oid, 'TRUNCATE');

  if v_com <> 545 then raise exception 'baseline errado: % com TRUNCATE (esperado 545)', v_com; end if;
  if v_sem <> 3   then raise exception 'baseline errado: % sem TRUNCATE (esperado 3)', v_sem; end if;
  if v_rls <> 548 then raise exception 'baseline errado: % com RLS (esperado 548)', v_rls; end if;
  if v_pol <> 0   then raise exception 'baseline errado: % policies (esperado 0)', v_pol; end if;
  if v_md5 <> 'e9368e7cd2d8095423234387ace01018' then
    raise exception 'baseline errado: md5 % (esperado e9368e7cd2d8095423234387ace01018 -- os nomes tem de ser os de producao)', v_md5;
  end if;
  raise notice 'baseline OK: 545 com TRUNCATE, 3 sem, 548 com RLS, 0 policy, md5 confere';
end
$$;

-- ===========================================================================
-- A PROVA QUE NÃO DEU PARA FAZER EM PRODUÇÃO: TRUNCATE ignora RLS.
-- Aqui pode, porque o banco é descartável.
-- ===========================================================================
do $$
declare v_select integer; v_delete integer; v_linhas integer;
begin
  set local role authenticated;

  -- RLS sem policy bloqueia leitura...
  select count(*) into v_select from public."_backup_pos_import_20260831";
  -- ...e a escrita linha a linha não alcança nada
  delete from public."_backup_pos_import_20260831";
  get diagnostics v_delete = row_count;

  -- ...mas TRUNCATE passa, porque é governado só pelo privilégio
  truncate table public."_backup_pos_import_20260831";

  reset role;

  select count(*) into v_linhas from public."_backup_pos_import_20260831";

  if v_select <> 0 then
    raise exception 'esperado 0 linha visivel por RLS, veio %', v_select;
  end if;
  if v_delete <> 0 then
    raise exception 'esperado DELETE afetar 0 linha por RLS, afetou %', v_delete;
  end if;
  if v_linhas <> 0 then
    raise exception 'TRUNCATE nao esvaziou a tabela (% linhas) -- a prova falhou', v_linhas;
  end if;

  raise notice 'PROVADO: com RLS ligada e 0 policy, authenticated ve 0 linha e seu DELETE afeta 0 linha, MAS seu TRUNCATE esvaziou a tabela';

  -- devolve a linha, para o resto do teste rodar com a tabela como as outras
  insert into public."_backup_pos_import_20260831" values (1, 'lastro financeiro');
end
$$;
