// QUEM SAIU DA EQUIPE SOME DO TELÃO — comportamento, no banco.
//
// Roda a migration REAL 20261007103000 contra um Postgres de verdade (pglite) e
// confere o payload que sai de tv_snapshot_atualizar(). O que estes casos
// protegem:
//
//   1. Olga (cobranca03) sai de TODOS os rankings e destaques de uma vez, via
//      v_ops — e os colegas continuam lá;
//   2. elogio dela não entra no telão nem se for aprovado;
//   3. música dela sai da Playlist ReATIVA;
//   4. aniversário e card de destaque saem do ar sem serem apagados;
//   5. NENHUM número financeiro muda — recuperado, honorários e meta somam
//      pagamentos inteiro, incluindo os dela;
//   6. a migration é idempotente e aborta se a âncora não existir.
//
// NENHUM DADO REAL de aluno. Os operadores são os e-mails de serviço da equipe.
import { describe, it, expect, beforeAll, vi } from "vitest";
import { PGlite } from "@electric-sql/pglite";
import { readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

// Subir uma instância pglite do zero passa dos 5 s padrão do vitest.
vi.setConfig({ testTimeout: 180000, hookTimeout: 600000 });

const AQUI = dirname(fileURLToPath(import.meta.url));
const ler = (p) => readFileSync(resolve(AQUI, "..", "..", p), "utf8");
const MIGRATION = ler("supabase/migrations/20261007103000_tv_equipe_oculta_sem_olga.sql");

const OLGA = "cobranca03@aelbra.com.br";
const COLEGA = "cobranca05@aelbra.com.br";
const GESTAO = "amanda.seibel@aelbra.com.br";

// Andaime: as tabelas que as duas funções tocam, e versões reduzidas de
// tv_snapshot_calcular/atualizar com os MESMOS trechos que a migration ancora —
// v_ops, a consulta de elogios e a de playlist. O resto do cálculo fica de fora
// porque não é o que está sob teste.
const ANDAIME = `
create schema if not exists auth;
create or replace function auth.jwt() returns jsonb language sql stable as $$
  select coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb, '{}'::jsonb) $$;
create or replace function auth.email() returns text language sql stable as $$ select auth.jwt()->>'email' $$;
create or replace function auth.role() returns text language sql stable as $$
  select coalesce(auth.jwt()->>'role','authenticated') $$;
do $$ begin
  if not exists (select 1 from pg_roles where rolname='authenticated') then create role authenticated; end if;
  if not exists (select 1 from pg_roles where rolname='anon') then create role anon; end if;
end $$;

create table public.tv_snapshot (
  id boolean primary key default true, versao bigint not null default 0, payload jsonb,
  status text, gerado_em timestamptz, gerado_por text, duracao_ms int, erro_resumo text);
create table public.tv_config (chave text primary key, valor jsonb, ativo boolean default true);
create table public.tv_aniversariantes (
  id bigint generated by default as identity primary key, nome text not null,
  dia integer, mes integer not null, ativo boolean not null default true);
create table public.portal_playlist (
  id uuid primary key default gen_random_uuid(), titulo text, artista text,
  adicionado_por text, adicionado_por_email text, criado_em timestamptz default now(),
  ativo boolean default true);
create table public.portal_eventos (
  id uuid primary key default gen_random_uuid(), titulo text, inicio_em timestamptz,
  categoria text, ativo boolean default true);
create table public.pagamentos (
  id bigint generated by default as identity primary key, data_pagamento date,
  valor_pago numeric, valor_honorario numeric, operador_email text, operador_nome text, cpf text);
create table public.aluno_movimentacoes (
  id bigint generated by default as identity primary key, status_novo text,
  elogio_aprovado_tv boolean default false, registrado_por_nome text,
  registrado_por_email text, registrado_em timestamptz default now(), elogio_print_path text);

create or replace function public.tv_snapshot_calcular()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare
  v_rec bigint; v_hon bigint; v_elogios jsonb; v_aniv jsonb; v_rank jsonb;
  v_ops text[] := array['cobranca03@aelbra.com.br','cobranca05@aelbra.com.br','cobranca06@aelbra.com.br',
                        'cobranca08@aelbra.com.br','cobranca10@aelbra.com.br','cobranca11@aelbra.com.br',
                        'cobranca12@aelbra.com.br','cobranca13@aelbra.com.br'];
  v_hoje date := (now() at time zone 'America/Sao_Paulo')::date;
begin
  -- FINANCEIRO: soma pagamentos INTEIRO, sem v_ops. É isto que não pode mudar.
  select coalesce(round(sum(valor_pago)),0)::bigint, coalesce(round(sum(valor_honorario)),0)::bigint
    into v_rec, v_hon from public.pagamentos where data_pagamento is not null;

  -- VITRINE: tudo aqui passa por v_ops.
  v_rank := jsonb_build_object(
    'ranking_mes', coalesce((select jsonb_agg(jsonb_build_object('operador', op, 'valor', vl) order by vl desc)
      from (select upper(coalesce(operador_nome, operador_email)) op, round(sum(valor_pago)) vl
              from public.pagamentos where lower(operador_email) = any(v_ops)
             group by 1) r), '[]'::jsonb),
    'melhor_mes', (select jsonb_build_object('operador', op) from (
        select upper(coalesce(operador_nome, operador_email)) op, sum(valor_pago) v
          from public.pagamentos where lower(operador_email) = any(v_ops)
         group by 1 order by v desc limit 1) a),
    'allowlist', to_jsonb(v_ops));

  select coalesce(jsonb_agg(jsonb_build_object('id',id,'registrado_por_nome',registrado_por_nome)
           order by registrado_em desc), '[]'::jsonb)
    into v_elogios
  from (select id, registrado_por_nome, registrado_em, elogio_print_path from public.aluno_movimentacoes
    where status_novo = 'ELOGIO_ATENDIMENTO' and elogio_aprovado_tv = true order by registrado_em desc limit 20) e;

  select coalesce(jsonb_agg(jsonb_build_object('nome', nome, 'dia', dia) order by nome), '[]'::jsonb)
    into v_aniv from public.tv_aniversariantes
  where ativo = true and mes = extract(month from v_hoje);

  return jsonb_build_object(
    'mes', jsonb_build_object('recuperado', v_rec, 'honorarios', v_hon),
    'rank', v_rank, 'elogios', v_elogios, 'aniversariantes', v_aniv);
end;
$function$;

create or replace function public.tv_snapshot_atualizar()
returns jsonb language plpgsql security definer set search_path to 'public'
set statement_timeout to '30s' as $function$
declare v_payload jsonb;
begin
  insert into public.tv_snapshot (id) values (true) on conflict (id) do nothing;
  v_payload := public.tv_snapshot_calcular();

  v_payload := v_payload || jsonb_build_object(
    'aniversario_destaque',
    (select valor from public.tv_config where chave = 'aniversario_destaque' and ativo = true limit 1));

  v_payload := v_payload || jsonb_build_object(
    'playlist_reativa',
    coalesce((
      select jsonb_agg(to_jsonb(x) order by x.criado_em desc)
      from (
        select id, titulo, artista, adicionado_por, criado_em
        from public.portal_playlist
        where ativo = true
        order by criado_em desc
        limit 6
      ) x
    ), '[]'::jsonb));

  update public.tv_snapshot set versao = versao + 1, payload = v_payload, status = 'ok' where id = true;
  return jsonb_build_object('status','ok');
end;
$function$;
`;

// Dados: Olga e um colega pagando no mesmo mês; elogio, música, aniversário e
// card de destaque dela no ar.
