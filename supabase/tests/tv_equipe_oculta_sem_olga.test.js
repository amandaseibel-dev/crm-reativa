async function novoBanco({ comMigration = true } = {}) {
  const db = new PGlite();
  await db.exec(ANDAIME);
  await db.exec(SEMENTE);
  if (comMigration) await db.exec(MIGRATION);
  await db.exec(`select set_config('request.jwt.claims','{"email":"${GESTAO}"}',false)`);
  return db;
}

async function atualizar(db) {
  await db.query("select public.tv_snapshot_atualizar()");
  const r = await db.query("select payload from public.tv_snapshot where id = true");
  return r.rows[0].payload;
}

const texto = (v) => JSON.stringify(v).toUpperCase();

let antes, depois;
beforeAll(async () => {
  const a = await novoBanco({ comMigration: false });
  antes = await atualizar(a);
  await a.close();
  depois = await novoBanco();
});

describe("a lista de quem não aparece no telão", () => {
  it("existe e nasce com a Olga", async () => {
    const r = await depois.query("select email, nome, motivo from public.tv_equipe_oculta order by email");
    expect(r.rows).toHaveLength(1);
    expect(r.rows[0].email).toBe(OLGA);
    expect(r.rows[0].nome).toBe("OLGA");
  });

  it("só aceita e-mail normalizado, e TRUNCATE não fica herdado", async () => {
    await expect(depois.query(
      "insert into public.tv_equipe_oculta(email, nome) values ('  Maiuscula@X.COM  ', 'X')"
    )).rejects.toThrow();
    const r = await depois.query(
      "select has_table_privilege('authenticated','public.tv_equipe_oculta','TRUNCATE') as pode");
    expect(r.rows[0].pode).toBe(false);
  });
});

describe("antes da migration, a Olga aparecia mesmo", () => {
  it("rankings, elogios, playlist, aniversário e destaque citavam o nome", async () => {
    expect(texto(antes.rank)).toContain("OLGA");
    expect(texto(antes.elogios)).toContain("OLGA");
    expect(texto(antes.playlist_reativa)).toContain("OLGA");
    expect(texto(antes.aniversariantes)).toContain("OLGA");
    expect(texto(antes.aniversario_destaque)).toContain("OLGA");
  });
});

describe("depois da migration, some de toda tela da TV", () => {
  it("o payload inteiro não cita mais a Olga", async () => {
    const p = await atualizar(depois);
    expect(texto(p)).not.toContain("OLGA");
    expect(texto(p)).not.toContain("COBRANCA03");
  });

  it("sai da allowlist — e os colegas continuam lá", async () => {
    const p = await atualizar(depois);
    expect(p.rank.allowlist).not.toContain(OLGA);
    expect(p.rank.allowlist).toContain(COLEGA);
    expect(p.rank.allowlist.length).toBe(7);
  });

  it("sai dos rankings e destaques; o colega assume", async () => {
    const p = await atualizar(depois);
    expect(texto(p.rank.ranking_mes)).not.toContain("OLGA");
    expect(p.rank.ranking_mes).toHaveLength(1);
    expect(p.rank.melhor_mes.operador).toBe("NATALY");  // era OLGA, que pagou mais
  });

  it("elogio dela não entra nem aprovado; o do colega fica", async () => {
    const p = await atualizar(depois);
    expect(texto(p.elogios)).not.toContain("OLGA");
    expect(texto(p.elogios)).toContain("NATALY");
  });

  it("música dela sai da playlist; a do colega fica", async () => {
    const p = await atualizar(depois);
    expect(texto(p.playlist_reativa)).not.toContain("OLGA");
    expect(texto(p.playlist_reativa)).toContain("NATALY");
  });

  it("aniversário e card de destaque saem do ar", async () => {
    const p = await atualizar(depois);
    expect(texto(p.aniversariantes)).not.toContain("OLGA");
    expect(texto(p.aniversariantes)).toContain("NATALY");
    expect(p.aniversario_destaque).toBeNull();
  });
});

describe("nada de histórico nem de dinheiro foi apagado", () => {
  it("os pagamentos dela continuam na tabela, intactos", async () => {
    const r = await depois.query(
      "select count(*)::int n, coalesce(sum(valor_pago),0)::text total from public.pagamentos where operador_email = $1", [OLGA]);
    expect(r.rows[0].n).toBe(1);
    expect(Number(r.rows[0].total)).toBe(30000);
  });

  it("recuperado e honorários do mês NÃO mudam — ela continua somando", async () => {
    const p = await atualizar(depois);
    expect(Number(p.mes.recuperado)).toBe(Number(antes.mes.recuperado));
    expect(Number(p.mes.honorarios)).toBe(Number(antes.mes.honorarios));
    expect(Number(p.mes.recuperado)).toBe(50000);   // 30.000 dela + 20.000 do colega
    expect(Number(p.mes.honorarios)).toBe(5000);
  });

  it("elogio, música e aniversário dela continuam no banco, só inativos", async () => {
    const e = await depois.query(
      "select count(*)::int n from public.aluno_movimentacoes where registrado_por_email = $1", [OLGA]);
    expect(e.rows[0].n).toBe(1);

    const m = await depois.query(
      "select count(*)::int n from public.portal_playlist where adicionado_por_email = $1", [OLGA]);
    expect(m.rows[0].n).toBe(1);

    const a = await depois.query(
      "select ativo from public.tv_aniversariantes where upper(nome) like '%OLGA%'");
    expect(a.rows).toHaveLength(1);
    expect(a.rows[0].ativo).toBe(false);

    const c = await depois.query(
      "select ativo from public.tv_config where chave = 'aniversario_destaque'");
    expect(c.rows[0].ativo).toBe(false);
  });
});

describe("a migration se comporta", () => {
  it("rodar de novo não quebra nem muda nada", async () => {
    const def = async () => (await depois.query(`
      select pg_get_functiondef(p.oid) src from pg_proc p join pg_namespace n on n.oid = p.pronamespace
       where n.nspname='public' and p.proname='tv_snapshot_calcular'`)).rows[0].src;
    const a = await def();
    await depois.exec(MIGRATION);
    expect(await def()).toBe(a);
    const linhas = await depois.query("select count(*)::int n from public.tv_equipe_oculta");
    expect(linhas.rows[0].n).toBe(1);
  });

  it("basta um INSERT para esconder a próxima pessoa — sem migration nova", async () => {
    await depois.query(
      "insert into public.tv_equipe_oculta(email, nome) values ($1, 'NATALY') on conflict do nothing", [COLEGA]);
    const p = await atualizar(depois);
    expect(texto(p.elogios)).not.toContain("NATALY");
    expect(texto(p.playlist_reativa)).not.toContain("NATALY");
    await depois.query("delete from public.tv_equipe_oculta where email = $1", [COLEGA]);
  });

  it("sem a âncora de v_ops, aborta em vez de mexer às cegas", async () => {
    const b = await novoBanco({ comMigration: false });
    await b.exec(`
      create or replace function public.tv_snapshot_calcular()
      returns jsonb language sql security definer set search_path to 'public'
      as $f$ select jsonb_build_object('mes', jsonb_build_object('recuperado', 1)) $f$;`);
    await expect(b.exec(MIGRATION)).rejects.toThrow(/ancora|aparece/i);
    await b.close();
  });
});

describe("o rollback devolve tudo", () => {
  it("desfaz os três filtros e a Olga volta aos rankings, elogios e playlist", async () => {
    const b = await novoBanco();
    const antesDoRollback = await atualizar(b);
    expect(texto(antesDoRollback)).not.toContain("OLGA");

    await b.exec(ler("supabase/rollbacks/20261007103000_tv_equipe_oculta_sem_olga.rollback.sql"));

    const p = await atualizar(b);
    expect(p.rank.allowlist).toContain(OLGA);
    expect(p.rank.allowlist.length).toBe(8);
    expect(texto(p.rank.ranking_mes)).toContain("OLGA");
    expect(texto(p.elogios)).toContain("OLGA");
    expect(texto(p.playlist_reativa)).toContain("OLGA");

    // A tabela some; as listas curadas seguem desligadas, como o arquivo avisa.
    const t = await b.query(
      "select to_regclass('public.tv_equipe_oculta') is null as sumiu");
    expect(t.rows[0].sumiu).toBe(true);
    const a = await b.query("select ativo from public.tv_aniversariantes where upper(nome) like '%OLGA%'");
    expect(a.rows[0].ativo).toBe(false);
    await b.close();
  });
});
