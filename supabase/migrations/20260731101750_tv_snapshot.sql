-- =============================================================================
-- TV ReATIVA — ARQUITETURA DE SNAPSHOT (sem polling, sem cálculo ao exibir)
-- =============================================================================
-- Objetivo: a TV deixa de calcular tudo AO VIVO (3 RPCs pesadas + 2 selects por
-- ciclo) e passa a LER UM ÚNICO snapshot leve (tv_snapshot_ler = 1 leitura).
-- A geração do snapshot ocorre SÓ quando Amanda/Fernanda clicam em "Atualizar
-- projeção" (mesmo gatilho da projeção e dos snapshots gerenciais).
--
-- Espelha o padrão já validado de projecao_snapshot / snapshot_gerencial:
--   * tabela com RLS deny-all (só as funções SECURITY DEFINER leem/escrevem);
--   * *_atualizar restrita por allowlist de e-mail (Amanda + Fernanda) com lock
--     de execução única e preservação do snapshot anterior em caso de falha;
--   * *_ler leve para a exibição.
--
-- AUTOSSUFICIENTE: o gerador NÃO chama dashboard_tv/dashboard_tv_projecao/
-- acionamentos_ranking (que existem apenas em produção, fora do versionamento).
-- A lógica dessas 3 RPCs foi trazida INLINE aqui (fiel à definição de produção),
-- de modo que a migration provisiona e valida de ponta a ponta também no staging.
-- As guardas abaixo criam apenas o que faltar; em produção viram no-op.
--
-- PRIVACIDADE: o payload da TV NÃO carrega CPF, telefone nem nome de aluno.
--   * maior_pagamento vai com aluno='' (idêntico à dashboard_tv de produção);
--   * elogios levam só autor (colaborador), data e caminho da imagem;
--   * aniversariantes são da EQUIPE (usuarios.aniversario), nunca de alunos.
--
-- NÃO APLICAR EM PRODUÇÃO sem autorização. Destinado a validação em staging.
-- =============================================================================

